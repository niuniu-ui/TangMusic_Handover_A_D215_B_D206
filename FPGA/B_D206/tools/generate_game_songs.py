"""Generate one millisecond timeline for B's rhythm judgement and drawing.

Pitches retain the existing eight-key excerpts. BPM values are practice tempos.
Modern titles use a rhythm arrangement, not an original score transcription.
Durations use eighth-note units: 1=eighth, 2=quarter, 3=dotted quarter, 4=half.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
COUNT_IN_BEATS = 4
HIT_Y = 395
SONGS = [
    dict(name="Scale exercise", bpm=100,
         lanes=[0,1,2,3,4,5,6,7,7,6,5,4,3,2,1,0], eighths=[2]*16),
    dict(name="Daoxiang - arranged excerpt", bpm=96,
         lanes=[2,4,4,4,4,4,4,4,4,4,2,1], eighths=[1,1,2,1,1,2,2,1,1,2,2,4]),
    dict(name="Qingtian - arranged excerpt", bpm=100,
         lanes=[4,4,0,0,1,2,4,4,0,0,1,2,1,0], eighths=[2,1,1,2,1,1,2,1,1,2,2,2,2,4]),
    dict(name="Qifengle - arranged excerpt", bpm=84,
         lanes=[1,0,1,0,1,2,4,2], eighths=[1,1,2,2,1,1,2,6]),
    dict(name="Pipa - arranged excerpt", bpm=108,
         lanes=[5,4,2,4,2,5,4,5,4,2,4,2], eighths=[1,1,2,1,1,2,2,1,1,2,2,4]),
    dict(name="Twinkle - familiar melody excerpt", bpm=100,
         lanes=[0,0,4,4,5,5,4,3,3,2,2,1,1,0,4,4,3,3,2,2,1,4,4,3,3,2,2,1],
         eighths=[2,2,2,2,2,2,4]*4),
    dict(name="Ode to Joy - familiar melody excerpt", bpm=120,
         lanes=[2,2,3,4,4,3,2,1,0,0,1,2,2,1,1,2,2,3,4,4,3,2,1,0,0,1,2,1,0,0],
         eighths=([2]*12+[3,1,4])*2),
    dict(name="User local excerpt - rhythm arrangement", bpm=112,
         lanes=[0,1,2,3,4,5,6,7,6,5,4,3,2,1,0,0,4,2,5,3,7,4,1,7],
         eighths=[1]*14+[2,4,1,1,2,1,1,2,2,4]),
]


def ms(eighths, bpm):
    """Round each absolute rational time once, without note-by-note drift."""
    return (eighths * 30000 + bpm // 2) // bpm


def scalar_function(name, bits, entries, default=0):
    lines = [f"function [{bits-1}:0] {name};input [2:0] song;begin case(song)"]
    lines += [f"  3'd{i}:{name}={bits}'d{value};" for i, value in enumerate(entries)]
    lines += [f"  default:{name}={bits}'d{default};endcase end endfunction"]
    return lines


def event_function(name, bits, values):
    lines = [f"function [{bits-1}:0] {name};input [2:0] song;input [5:0] idx;begin",
             "  case({song,idx})"]
    for sid, row in enumerate(values):
        lines += [f"    9'd{sid*64+i}:{name}={bits}'d{value};" for i, value in enumerate(row)]
    lines += [f"    default:{name}=0;endcase end endfunction"]
    return lines


def generate():
    onsets, durations, windows, ends, beats = [], [], [], [], []
    manifest = []
    for sid, song in enumerate(SONGS):
        assert len(song["lanes"]) == len(song["eighths"]) <= 63
        assert all(0 <= lane <= 7 for lane in song["lanes"])
        assert all(value > 0 for value in song["eighths"])
        units = COUNT_IN_BEATS * 2
        times, spans = [], []
        for duration in song["eighths"]:
            times.append(ms(units, song["bpm"]))
            spans.append(ms(units + duration, song["bpm"]) - times[-1])
            units += duration
        assert ms(units, song["bpm"]) < 65535
        # Leave at least one millisecond between neighboring hit windows.
        hit_windows = [min(180, (spans[i]-1)//2, (spans[i-1]-1)//2 if i else 180)
                       for i in range(len(times))]
        beat_times = [ms(i*2, song["bpm"]) for i in range((units+1)//2+3)]
        onsets.append(times);durations.append(spans);windows.append(hit_windows)
        ends.append(ms(units, song["bpm"]));beats.append(beat_times)
        manifest.append(dict(id=sid, **song, count_in_beats=COUNT_IN_BEATS,
                             original_score=False, onset_ms=times, duration_ms=spans,
                             good_window_ms=hit_windows, end_ms=ends[-1], beat_ms=beat_times))
    lines = ["// Generated by tools/generate_game_songs.py. Shared control/pixel timeline.",
             "// Practice arrangements/excerpts, not full original scores or recording tempos."]
    lines += scalar_function("game_length", 6, [len(s["lanes"]) for s in SONGS])
    lines += scalar_function("game_bpm", 8, [s["bpm"] for s in SONGS], default=100)
    lines += scalar_function("game_end_ms", 16, ends)
    lines += event_function("game_pattern", 8, [[1 << lane for lane in s["lanes"]] for s in SONGS])
    lines += event_function("game_onset_ms", 16, onsets)
    lines += event_function("game_duration_ms", 16, durations)
    lines += event_function("game_window_ms", 8, windows)
    lines += ["function [15:0] game_beat_time_ms;input [2:0] song;input [7:0] beat;begin",
              "  case({song,beat})"]
    for sid, row in enumerate(beats):
        lines += [f"    11'd{sid*256+i}:game_beat_time_ms=16'd{value};" for i, value in enumerate(row)]
    lines += ["    default:game_beat_time_ms=16'hffff;endcase end endfunction",
              "function [9:0] game_hit_y;input integer unused;begin game_hit_y=10'd395;end endfunction", ""]
    (ROOT / "src/studio_game_songs.vh").write_text("\n".join(lines), encoding="ascii")
    report = ROOT / "reports/rhythm_timing"
    report.mkdir(parents=True, exist_ok=True)
    (report / "timing_manifest.json").write_text(json.dumps(dict(count_in_beats=COUNT_IN_BEATS,
        judgement_y=HIT_Y, duration_unit="eighth note", songs=manifest), indent=2), encoding="utf8")
    print("Generated eight practice timelines, variable note lengths, four-beat count-in and exact beat boundaries")


if __name__ == "__main__":
    generate()
